def init_session_state():
    """Initialize and persist all platform state variables."""
    defaults = {
        "raw_df": None,
        "dataset_name": "None",
        "target_col": None,
        "positive_label": None,
        "id_col": None,
        "validation_result": None,
        "cleaned_X": None,
        "cleaned_y": None,
        "cleaning_report": None,
        "experiment_results": None,
        "global_shap_data": None,
        "explainer": None,
        "shap_model_name": None,
        "decision_threshold": 0.50,
        "enable_feature_engineering": True,
        "training_mode": "Quick",
        "class_imbalance": "balanced_weights",
    }
    for key, val in defaults.items():
        if key not in st.session_state:
            st.session_state[key] = val


def _resolve_page(rel_path: str) -> str:
    """Resolve page path relative to Streamlit's entrypoint directory."""
    ctx = get_script_run_ctx()
    if ctx and hasattr(ctx, "main_script_path") and ctx.main_script_path:
        main_dir = Path(ctx.main_script_path).resolve().parent
        if (main_dir / rel_path).exists():
            return rel_path
        if (main_dir / "app" / rel_path).exists():
            return f"app/{rel_path}"
    return rel_path


